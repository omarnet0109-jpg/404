"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const dir=path.resolve(__dirname,"..");
const script=fs.readFileSync(path.join(dir,"ai-speakers.js"),"utf8");
const app=fs.readFileSync(path.join(dir,"simple.js"),"utf8");
const editor=fs.readFileSync(path.join(dir,"episode-editor.js"),"utf8");
const html=fs.readFileSync(path.join(dir,"episode-editor.html"),"utf8");
const home=fs.readFileSync(path.join(dir,"index.html"),"utf8");
const store=new Map();
const localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>{store.set(k,v)}};
const context={localStorage};
vm.createContext(context);
vm.runInContext(script,context);
const cast=context.Studio404AISpeakers;
assert.equal(cast.get("LAYLA").speaker,"Yasmin");
assert.equal(cast.get("WIDAD").speaker,"Hanan");
assert.equal(cast.get("SABER").speaker,"Shaker");
assert.equal(new Set(["LAYLA","WIDAD","SABER"].map(id=>cast.identity(id))).size,3);
assert.match(cast.identity("LAYLA"),/^demo:mohammedaly22\/VoiceTut-TTS:Yasmin$/);
assert.throws(()=>cast.assign("WIDAD","Yasmin",{replace:true}),/تانية/);
assert.throws(()=>cast.assign("LAYLA","Rana"),/موافقة صريحة/);
cast.assign("LAYLA","Rana",{replace:true});
assert.equal(cast.get("LAYLA").speaker,"Rana");
assert.equal(cast.identity("LAYLA"),"demo:mohammedaly22/VoiceTut-TTS:Rana");
assert.equal(cast.get("WIDAD").speaker,"Hanan");
assert.throws(()=>cast.assign("C_a1234","Rana"),/تانية/);
cast.assign("C_a1234","Yara");
assert.equal(cast.get("C_a1234").speaker,"Yara");
assert.equal(cast.get("C_a1234").locked,true);
assert.equal(cast.get("C_a1234").demo,true);
assert.equal(cast.get("INVALID"),null);
assert.match(home,/id="aiVoiceSelect"/);
assert.match(home,/id="saveAiVoice"/);
assert.match(home,/غير مرخّصة للنشر التجاري/);
assert.match(app,/Studio404AISpeakers\.assign\(id,speaker/);
assert.match(html,/id="voiceMode"/);
assert.match(html,/value="demo"/);
assert.match(html,/id="licensedTranscript" hidden/);
assert.match(html,/id="generateDialogue"/);
assert.match(html,/id="spokenText"/);
assert.match(html,/غير مرخّصة للنشر التجاري|غير مرخصة للنشر التجاري/);
assert.match(editor,/mode==="licensed"\?"clone":"builtin"/);
assert.match(editor,/preset\?\.speaker\|\|""/);
assert.match(editor,/source\?handle_file\(source\):null/);
assert.match(editor,/globalThis\.Studio404AISpeakers\.identity\(v\.actor\)/);
assert.match(editor,/voice\.referenceHash!==expected/);
assert.match(editor,/await saveSound\(output,\{source:"voicetut",referenceHash:voiceIdentity\}\)/);
assert.match(editor,/if\(!\$\("audioConsent"\)\.checked\)/);
console.log("PASS: 3 distinct persistent AI voices, commercial trial warning, actor-specific synthesis & saved dialogue guard");
